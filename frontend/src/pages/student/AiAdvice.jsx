import { useState } from "react";
import api, { errorText } from "../../api/client";

export default function AiAdvice() {
  const [res, setRes] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);

  const getAdvice = async () => {
    setBusy(true);
    setError(null);
    try {
      const { data } = await api.get("/student/ai-advice");
      setRes(data);
    } catch (err) {
      setError(errorText(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    <>
      <h2>AI Study Advice</h2>
      <p className="muted">
        Personal suggestions based on your published marks and attendance.
      </p>
      <button className="btn" onClick={getAdvice} disabled={busy}>
        {busy ? "Thinking... (can take a minute)" : "Get my advice"}
      </button>
      {error && <p className="error">{error}</p>}

      {res && (
        <div className="card" style={{ marginTop: 16 }}>
          <span className="badge">
            {res.source === "ai" ? "Generated by AI model" : "Rule-based (start Ollama for AI)"}
          </span>
          <p style={{ whiteSpace: "pre-wrap" }}>{res.advice}</p>
          {res.weak_subjects.length > 0 && (
            <p><strong>Weak subjects:</strong> {res.weak_subjects.join(", ")}</p>
          )}
          {res.low_attendance.length > 0 && (
            <p><strong>Low attendance:</strong> {res.low_attendance.join(", ")}</p>
          )}
        </div>
      )}
    </>
  );
}